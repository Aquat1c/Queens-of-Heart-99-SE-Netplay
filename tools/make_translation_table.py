"""Generate src/i18n/TrTableJa.inc from a JSON translation list.

Input: a JSON array of {"en": "...", "ja": "..."} objects, in any order.
Output: a sorted C table the lookup can binary-search.

    python tools/make_translation_table.py translations.json

The sort is by the UTF-8 BYTES of the English key, because the lookup uses
strcmp; sorting by anything else (Python's default str ordering happens to
agree for ASCII, and does NOT for the rest) would silently make entries
unfindable rather than fail loudly.
"""
import json
import os
import sys

HEX = set('0123456789abcdefABCDEF')

def c_literal(text):
    out = ['"']
    previous_was_hex_escape = False
    for byte in text.encode('utf-8'):
        char = chr(byte)
        if byte < 0x20 or byte == 0x7F or byte >= 0x80:
            out.append('\\x%02X' % byte)
            previous_was_hex_escape = True
            continue
        if char == '"' or char == '\\':
            out.append('\\' + char)
            previous_was_hex_escape = False
            continue
        if previous_was_hex_escape and char in HEX:
            out.append('" "')
        out.append(char)
        previous_was_hex_escape = False
    out.append('"')
    return ''.join(out)

def main(argv):
    if len(argv) != 2:
        print(__doc__)
        return 2
    with open(argv[1], encoding='utf-8') as handle:
        entries = json.load(handle)

    rows = {}
    for entry in entries:
        english = entry.get('en', '')
        japanese = entry.get('ja', '')
        if not english or not japanese:
            continue
        if japanese == english:
            continue
        rows[english] = japanese

    ordered = sorted(rows.items(), key=lambda pair: pair[0].encode('utf-8'))

    here = os.path.dirname(os.path.abspath(__file__))
    target = os.path.join(here, '..', 'src', 'i18n', 'TrTableJa.inc')
    with open(target, 'w', encoding='utf-8', newline='\n') as out:
        out.write('// GENERATED by tools/make_translation_table.py - '
                  'do not edit by hand.\n')
        out.write('//\n')
        out.write('// Sorted by the UTF-8 bytes of the English key, because '
                  'the lookup is a\n')
        out.write('// strcmp binary search. Entries whose translation equals '
                  'the English are\n')
        out.write('// omitted: a miss already returns the key.\n')
        out.write('constexpr Row kJapaneseRows[] = {\n')
        for english, japanese in ordered:
            out.write('    {%s,\n     %s},\n'
                      % (c_literal(english), c_literal(japanese)))
        out.write('};\n')
        out.write('constexpr std::size_t kJapaneseRowCount =\n'
                  '    sizeof(kJapaneseRows) / sizeof(kJapaneseRows[0]);\n')
    print('wrote %s (%d rows)' % (os.path.normpath(target), len(ordered)))
    return 0

if __name__ == '__main__':
    sys.exit(main(sys.argv))
